/* ---------------------------------------------------------------------------
   www 归一到主域名
   ---------------------------------------------------------------------------
   必须以 **同源外部文件** 的形式在 <head> 里同步加载 —— 不能写成内联 <script>。

   为什么（两个都踩过）：
   1) 线上响应头带 CSP `script-src 'self'`，内联脚本会被**直接拦掉**：
      它还在 DOM 里、控制台也不报错，就是不执行，非常难查。
      换成同源 .js 文件即符合该策略，无需放开 'unsafe-inline'。
   2) `6.中国` 和 `www.6.中国` 在浏览器眼里是**两个不同的 origin**，
      localStorage / IndexedDB 按 origin 隔离。不归一的话，设备名和配对记忆
      在两边各存一份，用户看到的现象就是「改名没生效 / 配对丢了」。

   必须同步（不能 defer/async）：要在首次绘制之前跳走，否则会闪一下。

   保留 path / search / hash：配对链接是 `https://6.中国/#pair=123456` 这种形式，
   hash 丢了配对就废了。
--------------------------------------------------------------------------- */
(function () {
  try {
    var u = new URL(location.href);
    // 只剥一层 www.，避免 www.www.x 来回弹
    if (u.hostname.slice(0, 4).toLowerCase() === 'www.') {
      u.hostname = u.hostname.slice(4);
      location.replace(u.href);
    }
  } catch (e) { /* 环境异常就静默放过，别把页面卡死 */ }
})();
