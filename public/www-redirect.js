/* ---------------------------------------------------------------------------
   把「同一站点的各种域名写法」归一到主域名
   ---------------------------------------------------------------------------
   必须以 **同源外部文件** 的形式在 <head> 里同步加载 —— 不能写成内联 <script>。

   为什么（三个坑都踩过）：
   1) 线上响应头带 CSP `script-src 'self'`，内联脚本会被**直接拦掉**：
      它还在 DOM 里、控制台也不报错，就是不执行，非常难查。
      换成同源 .js 文件即符合该策略，无需放开 'unsafe-inline'。
   2) `x.com` 和 `www.x.com` 在浏览器眼里是**两个不同的 origin**，
      localStorage / IndexedDB 按 origin 隔离。不归一的话，设备名和配对记忆
      在两边各存一份，用户看到的现象就是「改名没生效 / 配对丢了」。
   3) `.中国`(xn--fiqs8s) 和 `.中國`(xn--fiqz9s) 是**两个不同的顶级域**，
      虽然 CNNIC 把注册数据当成一份（简繁等效），但浏览器不认这层关系 ——
      对浏览器来说同样是两个 origin，同样会各存一份状态。

   必须同步（不能 defer/async）：要在首次绘制之前跳走，否则会闪一下。

   保留 path / search / hash：配对链接是 `https://6.中国/#pair=123456` 这种形式，
   hash 丢了配对就废了。
--------------------------------------------------------------------------- */
(function () {
  try {
    var CANON = '6.xn--fiqs8s';                    // 主域名：6.中国
    var FAMILY = ['6.xn--fiqs8s', '6.xn--fiqz9s']; // 简繁两个顶级域下的同一个站

    var u = new URL(location.href);
    var h = u.hostname.toLowerCase();

    // 剥掉一层 www.
    var base = h.slice(0, 4) === 'www.' ? h.slice(4) : h;

    // ⚠️ 用白名单而不是「只要不是主域名就跳」：
    //    否则本地开发（127.0.0.1）、workers.dev 备用入口、
    //    以及将来任何新绑的域名都会被硬拽到主域名上。
    if (h !== CANON && FAMILY.indexOf(base) !== -1) {
      u.hostname = CANON;
      location.replace(u.href);
    }
  } catch (e) { /* 环境异常就静默放过，别把页面卡死 */ }
})();
